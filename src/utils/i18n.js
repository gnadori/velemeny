export function getSavedLanguage() {
  const saved = localStorage.getItem('velemeny_lang');
  if (saved && ['hu', 'en', 'ro'].includes(saved)) {
    return saved;
  }
  return 'hu';
}

export function saveLanguage(lang) {
  localStorage.setItem('velemeny_lang', lang);
}
